"""
Builds src/main/resources/assets/zeus/ai/recipes.txt from the game's own recipe and item tag files, so Zeus AI
knows every vanilla recipe in single player and on servers alike, unlocked or not.

  python3 tools/ai/make_recipes.py <minecraft jar>

Line formats (ids without the minecraft: prefix, a cell is item, #tag, or a|b alternatives, empty for a gap):
  C|result|count|width|height|cell;cell;...     shaped crafting, row by row
  S|result|count|ing;ing;...                     shapeless crafting
  F|result|count|input                           furnace (smelting)
  X|result|count|input                           stonecutter
  M|result|template|base|addition                smithing table upgrade
  G|tag|item,item,...                            item tag members (tags inside tags expanded)
"""
import json, sys, zipfile, os

jar = zipfile.ZipFile(sys.argv[1])
names = jar.namelist()

def strip(i):
    return i[10:] if i.startswith('minecraft:') else i

def load(n):
    return json.loads(jar.read(n))

# ---- tags
raw_tags = {}
for n in names:
    if n.startswith('data/minecraft/tags/item/') and n.endswith('.json'):
        tag = n[len('data/minecraft/tags/item/'):-5]
        vals = []
        for v in load(n)['values']:
            if isinstance(v, dict): v = v['id']
            vals.append(strip(v) if not v.startswith('#') else '#' + strip(v[1:]))
        raw_tags[tag] = vals

def expand(tag, seen=()):
    out = []
    for v in raw_tags.get(tag, []):
        if v.startswith('#'):
            if v[1:] not in seen: out += expand(v[1:], seen + (tag,))
        else:
            out.append(v)
    return out

used_tags = set()

def cell(spec):
    """An ingredient: a string, a list of alternatives, or (old style) {"item"/"tag"}."""
    if spec is None or spec == '': return ''
    if isinstance(spec, list):
        return '|'.join(cell(s) for s in spec)
    if isinstance(spec, dict):
        if 'tag' in spec: spec = '#' + spec['tag']
        else: spec = spec['item']
    if spec.startswith('#'):
        t = strip(spec[1:])
        used_tags.add(t)
        return '#' + t
    return strip(spec)

lines = []
for n in sorted(names):
    if not (n.startswith('data/minecraft/recipe/') and n.endswith('.json')): continue
    r = load(n)
    t = strip(r['type'])
    res = r.get('result', {})
    rid = strip(res['id']) if isinstance(res, dict) and 'id' in res else None
    cnt = res.get('count', 1) if isinstance(res, dict) else 1
    if t == 'crafting_shaped':
        pat = r['pattern']
        w, h = max(len(p) for p in pat), len(pat)
        cells = []
        for row in pat:
            for ch in row.ljust(w):
                cells.append('' if ch == ' ' else cell(r['key'][ch]))
        lines.append(f'C|{rid}|{cnt}|{w}|{h}|' + ';'.join(cells))
    elif t == 'crafting_shapeless':
        lines.append(f'S|{rid}|{cnt}|' + ';'.join(cell(i) for i in r['ingredients']))
    elif t == 'smelting':
        lines.append(f'F|{rid}|{cnt}|' + cell(r['ingredient']))
    elif t == 'stonecutting':
        lines.append(f'X|{rid}|{cnt}|' + cell(r['ingredient']))
    elif t == 'smithing_transform':
        lines.append(f'M|{rid}|{cell(r["template"])}|{cell(r["base"])}|{cell(r["addition"])}')
for tag in sorted(used_tags):
    members = expand(tag)
    if members: lines.append(f'G|{tag}|' + ','.join(dict.fromkeys(members)))

out = 'src/main/resources/assets/zeus/ai/recipes.txt'
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('# generated by tools/ai/make_recipes.py from Minecraft 1.21.11, do not edit by hand\n')
    f.write('\n'.join(lines) + '\n')
kinds = {}
for l in lines: kinds[l[0]] = kinds.get(l[0], 0) + 1
print(out, kinds, os.path.getsize(out), 'bytes')
